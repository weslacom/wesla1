create table if not exists public.wesla_feature_settings (
  feature_key varchar(40) primary key,
  is_enabled boolean not null default false,
  audience jsonb not null default '[]'::jsonb,
  config jsonb not null default '{}'::jsonb,
  updated_at timestamptz not null default now()
);
create table if not exists public.wesla_reward_accounts (
  user_id bigint primary key references public.users(id) on delete cascade,
  points_available bigint not null default 0 check (points_available >= 0),
  points_pending bigint not null default 0 check (points_pending >= 0),
  lifetime_earned bigint not null default 0 check (lifetime_earned >= 0),
  tier varchar(20) not null default 'basic',
  updated_at timestamptz not null default now()
);
create table if not exists public.wesla_reward_ledger (
  id bigint generated by default as identity primary key,
  user_id bigint not null references public.users(id) on delete cascade,
  delta bigint not null check (delta <> 0),
  status varchar(16) not null default 'posted' check (status in ('pending','posted','reversed')),
  event_key varchar(160) not null unique,
  source_type varchar(40) not null,
  source_id bigint,
  description varchar(240) not null default '',
  expires_at timestamptz,
  created_at timestamptz not null default now()
);
create index if not exists wesla_reward_ledger_user_created_idx on public.wesla_reward_ledger(user_id,created_at desc);
create table if not exists public.wesla_referral_codes (
  user_id bigint primary key references public.users(id) on delete cascade,
  code varchar(24) not null unique,
  created_at timestamptz not null default now()
);
create table if not exists public.wesla_referrals (
  id bigint generated by default as identity primary key,
  referrer_user_id bigint not null references public.users(id) on delete cascade,
  referred_user_id bigint not null unique references public.users(id) on delete cascade,
  referral_code varchar(24) not null,
  status varchar(20) not null default 'registered' check (status in ('registered','qualified','rejected')),
  reward_points bigint not null default 0 check (reward_points >= 0),
  qualified_at timestamptz,
  created_at timestamptz not null default now(),
  check (referrer_user_id <> referred_user_id)
);
create index if not exists wesla_referrals_referrer_created_idx on public.wesla_referrals(referrer_user_id,created_at desc);
create table if not exists public.wesla_trend_events (
  id bigint generated by default as identity primary key,
  product_id bigint not null references public.products(id) on delete cascade,
  user_id bigint references public.users(id) on delete set null,
  visitor_hash varchar(64) not null,
  event_type varchar(16) not null check (event_type in ('view','favorite','order','share')),
  created_at timestamptz not null default now()
);
create index if not exists wesla_trend_events_product_created_idx on public.wesla_trend_events(product_id,created_at desc);
create index if not exists wesla_trend_events_created_idx on public.wesla_trend_events(created_at desc);
create table if not exists public.wesla_challenges (
  id bigint generated by default as identity primary key,
  title varchar(180) not null,
  description text not null default '',
  starts_at timestamptz not null,
  ends_at timestamptz not null,
  reward_points bigint not null default 0 check (reward_points >= 0),
  criteria jsonb not null default '{}'::jsonb,
  is_active boolean not null default false,
  created_at timestamptz not null default now(),
  check (ends_at > starts_at)
);
create table if not exists public.wesla_challenge_participations (
  id bigint generated by default as identity primary key,
  challenge_id bigint not null references public.wesla_challenges(id) on delete cascade,
  user_id bigint not null references public.users(id) on delete cascade,
  progress jsonb not null default '{}'::jsonb,
  status varchar(16) not null default 'joined' check (status in ('joined','completed','rejected')),
  completed_at timestamptz,
  created_at timestamptz not null default now(),
  unique(challenge_id,user_id)
);
create table if not exists public.wesla_achievements (
  id bigint generated by default as identity primary key,
  code varchar(60) not null unique,
  title varchar(120) not null,
  description text not null default '',
  criteria jsonb not null default '{}'::jsonb,
  is_active boolean not null default true
);
create table if not exists public.wesla_user_achievements (
  id bigint generated by default as identity primary key,
  user_id bigint not null references public.users(id) on delete cascade,
  achievement_id bigint not null references public.wesla_achievements(id) on delete cascade,
  awarded_at timestamptz not null default now(),
  unique(user_id,achievement_id)
);
create table if not exists public.wesla_academy_content (
  id bigint generated by default as identity primary key,
  title varchar(180) not null,
  content_type varchar(20) not null check (content_type in ('article','video','quiz')),
  audience varchar(20) not null default 'all' check (audience in ('all','customer','merchant','affiliate')),
  body text not null default '',
  media_url text not null default '',
  is_published boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create table if not exists public.wesla_ai_usage (
  id bigint generated by default as identity primary key,
  user_id bigint references public.users(id) on delete set null,
  feature_key varchar(60) not null,
  provider varchar(60) not null default 'not_configured',
  input_tokens integer not null default 0,
  output_tokens integer not null default 0,
  estimated_cost numeric(14,6) not null default 0,
  status varchar(20) not null default 'logged',
  created_at timestamptz not null default now()
);
create index if not exists wesla_ai_usage_created_idx on public.wesla_ai_usage(created_at desc);
